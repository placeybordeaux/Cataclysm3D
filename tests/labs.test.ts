// Machinery on a flat test map

class FlatGen implements ChunkGenerator {
  generate(map: GameMap, c: Chunk): void {
    c.ter.fill(map.terrain.index(c.z > 0 ? 't_open_air' : 't_linoleum_white'));
    c.empty = false;
  }
}
function fakeInput(): Input {
  return { held: new Set<string>(), captured: false, mouseButtons: 0, onPress() {}, consumeMouse: () => [0, 0], consumeClicks: () => [] } as unknown as Input;
}
function flat() {
  const game = new Game(data, 3, fakeInput());
  game.map.generator = new FlatGen();
  game.player.x = 10.5;
  game.player.y = 10.5;
  game.player.z = 0;
  const msgs: string[] = [];
  game.events.on('message', (m) => msgs.push(m.text));
  return { game, msgs };
}

// These exercise the machinery against DDA-shaped data (JSON "cardreader" examine actors,
// f_console furniture, boom barriers). BN hardcodes card readers in C++ and makes consoles
// terrain (t_console), so each runs only while the data it needs is present.
const hasTer = (id: string) => !!data.terrain[id];
const hasFurn = (id: string) => !!data.furniture[id];
const cardreaderData = hasTer('t_card_science') && !!cardreaderOf(data.terrain.t_card_science as any);

describe('lab machinery', () => {
  it.runIf(cardreaderData)('a science card opens the metal doors around its reader and the reader stays', async () => {
    const { game, msgs } = flat();
    game.map.setTer(12, 10, 0, 't_card_science');
    game.map.setTer(13, 11, 0, 't_door_metal_locked');
    game.map.setTer(20, 10, 0, 't_door_metal_locked');
    const cr = cardreaderOf(game.map.terAt(12, 10, 0))!;
    expect(cr.flags).toContain('SCIENCE_CARD');
    expect(await useCardreader(game, 12, 10, 0, cr, autoUi(game))).toBe('none');
    game.player.inv.pickUp(createItem(data, 'id_science'));
    expect(await useCardreader(game, 12, 10, 0, cr, autoUi(game))).toBe('opened');
    expect(game.map.terAt(13, 11, 0).id).toBe('t_door_metal_c');
    // outside radius 3: untouched
    expect(game.map.terAt(20, 10, 0).id).toBe('t_door_metal_locked');
    expect(msgs.some((m) => /doors unlock/.test(m))).toBe(true);
    expect(await useCardreader(game, 12, 10, 0, cr, autoUi(game))).toBe(cr.consume_card === false ? 'redundant' : 'none');
  });

  it('card readers apply their terrain_changes within the radius', () => {
    const { game } = flat();
    const def: CardreaderDef = { type: 'cardreader', flags: ['X'], radius: 2, terrain_changes: { t_door_metal_locked: 't_door_metal_c' } };
    game.map.setTer(11, 10, 0, 't_door_metal_locked');
    game.map.setTer(14, 10, 0, 't_door_metal_locked');
    expect(applyCardreader(game, 10, 10, 0, def)).toBe(true);
    expect(game.map.terAt(11, 10, 0).id).toBe('t_door_metal_c');
    expect(game.map.terAt(14, 10, 0).id).toBe('t_door_metal_locked');
  });

  it('a skilled hacker with an electrohack gets through; the reader is burnt out', () => {
    const { game } = flat();
    game.map.setTer(12, 10, 0, 't_card_science');
    game.map.setTer(12, 11, 0, 't_door_metal_locked');
    const tool = createItem(data, 'electrohack');
    game.player.setSkill('computer', 10);
    game.player.int_base = 14;
    // level 10 + 0 + 7 - 8 = 9 vs threshold 6 with sd 5: mostly success
    let ok = 0;
    for (let i = 0; i < 20; i++) {
      game.map.setTer(12, 10, 0, 't_card_science');
      game.map.setTer(12, 11, 0, 't_door_metal_locked');
      if (finishHack(game, 12, 10, 0, tool) === 'success') {
        ok++;
        expect(game.map.terAt(12, 11, 0).id).toBe('t_door_metal_c');
        expect(game.map.terAt(12, 10, 0).id).toBe('t_card_reader_broken');
      }
    }
    expect(ok).toBeGreaterThan(8);
  });

  it.runIf(hasFurn('f_console'))('consoles: failing to bypass security triggers a failure, success unlocks nearby doors', async () => {
    const { game, msgs } = flat();
    game.map.setFurn(11, 10, 0, 'f_console');
    game.map.setTer(15, 10, 0, 't_door_metal_locked');
    const c = game.map.chunk(0, 0, 0)!;
    const comp = { name: 'Test terminal', security: 0, options: [{ name: 'UNLOCK ENTRANCE', action: 'unlock' }], failures: [{ action: 'shutdown' }] };
    c.computers.set(10 * CHUNK + 11, comp);
    await useComputer(game, 11, 10, 0, autoUi(game));
    expect(game.map.terAt(15, 10, 0).id).toBe('t_door_metal_c');
    expect(msgs.some((m) => /Lock disabled/.test(m))).toBe(true);
    // security 50: a novice never gets in and the console shuts down
    comp.security = 50;
    game.player.setSkill('computer', 0);
    await useComputer(game, 11, 10, 0, autoUi(game));
    expect(game.map.furnAt(11, 10, 0).id).toBe('f_console_broken');
  });

  it('research notes come from lab_notes snippets and raise alerts', () => {
    const { game } = flat();
    const comp: any = { options: [] };
    const text = computerAction(game, 10, 10, 0, comp, 'research');
    expect(data.misc.snippet.lab_notes.some((s: string) => text.startsWith(s.slice(0, 40)))).toBe(true);
    expect(comp.alerts).toBe(1);
  });

  it('gate controls open and close the gate (gates.json)', () => {
    const { game } = flat();
    // control on a wall line: wall at (11,10), gate door tiles run south from (11,11)
    game.map.setTer(10, 10, 0, 't_gates_mech_control_lab');
    game.map.setTer(11, 10, 0, 't_concrete_wall');
    for (let y = 11; y <= 13; y++) game.map.setTer(11, y, 0, 't_door_metal_locked');
    game.map.setTer(11, 14, 0, 't_concrete_wall');
    game.player.x = 9.5;
    expect(toggleGate(game, 10, 10, 0, data.misc.gate.t_gates_mech_control_lab)).toBe('open');
    expect(game.map.terAt(11, 12, 0).id).toBe('t_thconc_floor');
    expect(toggleGate(game, 10, 10, 0, data.misc.gate.t_gates_mech_control_lab)).toBe('close');
    expect(game.map.terAt(11, 12, 0).id).toBe('t_door_metal_locked');
  });

  it('elevators move the survivor (and items) between floors with powered controls', () => {
    const { game } = flat();
    for (const z of [0, -2]) {
      for (let y = 10; y <= 11; y++) for (let x = 10; x <= 11; x++) game.map.setTer(x, y, z, 't_elevator');
      game.map.setTer(12, 10, z, 't_elevator_control');
    }
    game.map.setTer(12, 10, -1, 't_rock');
    const floors = elevatorFloors(game, 12, 10, 0);
    expect(floors.map((f) => f.z)).toEqual([0, -2]);
    game.player.x = 5.5;
    expect(rideElevator(game, 12, 10, 0, -2)).toMatch(/stand inside/);
    game.player.x = 11.5;
    game.player.y = 10.5;
    const it = createItem(data, 'rock');
    game.map.addItem(10, 11, 0, it);
    expect(rideElevator(game, 12, 10, 0, -2)).toBeNull();
    expect(game.player.z).toBe(-2);
    expect(game.player.tileX).toBe(11);
    expect(game.map.itemsAt(10, 11, -2)).toContain(it);
    // an unpowered control is not a floor
    game.map.setTer(12, 10, 0, 't_elevator_control_off');
    expect(elevatorFloors(game, 12, 10, -2).map((f) => f.z)).toEqual([-2]);
  });

  it.runIf(hasTer('t_boom_barrier_lowered'))('climbing over a boom barrier puts you on the far side', () => {
    const { game } = flat();
    game.map.setTer(11, 10, 0, 't_boom_barrier_lowered');
    expect(hasFlag(game.map.terAt(11, 10, 0), 'CLIMBABLE')).toBe(true);
    expect(climbOver(game, 11, 10, 0)).toBeNull();
    expect(game.player.tileX).toBe(12);
  });
});
