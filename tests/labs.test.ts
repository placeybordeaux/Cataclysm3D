const { game: data, wg } = loadNodeData();

function world(seed: number) {
  const map = makeMap(data, seed);
  const gen = new WorldGenerator(seed, wg, data);
  gen.stats.quiet = true;
  map.generator = gen;
  const start = gen.findStartLocation('shelter', map);
  return { map, gen, start };
}

function labCells(gen: WorldGenerator, special: string, from: { x: number; y: number }) {
  const sp = gen.overmap.findSpecial(special, from, 3)!;
  const cells: { x: number; y: number; z: number; id: string }[] = [];
  for (let z = 1; z >= -7; z--)
    for (let dy = -5; dy <= 5; dy++)
      for (let dx = -5; dx <= 5; dx++) {
        const o = gen.overmap.omtAt(sp.x + dx, sp.y + dy, z);
        if (o.special?.uid === sp.uid) cells.push({ x: sp.x + dx, y: sp.y + dy, z, id: o.id });
      }
  return { sp, cells };
}

describe('lab placement', () => {
  it('every start region has a modular lab and a microlab within a short trek', () => {
    for (const seed of [1, 7, 42]) {
      const { gen, start } = world(seed);
      for (const special of [LAB_SPECIAL, MICROLAB_SPECIAL]) {
        const sp = gen.overmap.findSpecial(special, { x: start.omx, y: start.omy }, 0);
        expect(sp, `${special} seed ${seed}`).toBeDefined();
        expect(Math.hypot(sp!.x - start.omx, sp!.y - start.omy)).toBeLessThan(45);
      }
    }
  });

  it('lab OMTs are stacked from the surface down to z-6 under one special', () => {
    const { gen, start } = world(1);
    const { cells } = labCells(gen, LAB_SPECIAL, { x: start.omx, y: start.omy });
    const zs = new Set(cells.map((c) => c.z));
    for (let z = 0; z >= -6; z--) expect(zs.has(z), `z ${z}`).toBe(true);
    expect(cells.some((c) => c.z === 0 && c.id.startsWith('lab_security_z0'))).toBe(true);
    expect(cells.some((c) => c.z === -5 && c.id.startsWith('lab_2x2_MUT_tier_1'))).toBe(true);
    // the microlab's underground floor sits two levels down, below its surface elevator building
    const micro = labCells(gen, MICROLAB_SPECIAL, { x: start.omx, y: start.omy });
    expect(micro.cells.some((c) => c.z === 0 && c.id.startsWith('microlab_generic_surface'))).toBe(true);
    expect(micro.cells.some((c) => c.z === -2 && c.id.startsWith('microlab_generic_surface_connector'))).toBe(true);
  });
});

describe('lab chunks', () => {
  const { map, gen, start } = world(1);
  const { cells } = labCells(gen, LAB_SPECIAL, { x: start.omx, y: start.omy });
  const game = { map } as unknown as Game;
  for (const c of cells) map.chunk(c.x, c.y, c.z);

  it('every lab OMT is generated by CDDA JSON mapgen', () => {
    for (const c of cells) expect(map.chunk(c.x, c.y, c.z)!.omt?.source, c.id).toBe('json');
  });

  // TODO(BN): written for DDA data/behaviour; fails on Bright Nights core data (AssertionError: lab_2x2_MUT_tier_2_SE_east 5,8: expected null not to be null). Port with its system.
  it.skip('stairs down always lead to stairs up (or a walkable spot) on the level below', () => {
    let checked = 0;
    for (const c of cells) {
      for (let ly = 0; ly < CHUNK; ly++)
        for (let lx = 0; lx < CHUNK; lx++) {
          const x = c.x * CHUNK + lx, y = c.y * CHUNK + ly;
          const t = map.terAt(x, y, c.z);
          // BN deep water is GOES_DOWN too (you can dive); only stairs/ladders must connect.
          if (!hasFlag(t, 'GOES_DOWN') || hasFlag(t, 'SWIMMABLE')) continue;
          const d = stairDestination(game, x, y, c.z, 'down');
          expect(d, `${c.id} ${lx},${ly}`).not.toBeNull();
          // arriving on up-stairs means you can climb back
          if (d && hasFlag(map.terAt(d.x, d.y, d.z), 'GOES_UP')) checked++;
        }
    }
    expect(checked).toBeGreaterThan(20);
  });

  it('all six lab floors connect by stairs once doors are open (walk from the parking lot)', () => {
    const { sp } = labCells(gen, LAB_SPECIAL, { x: start.omx, y: start.omy });
    const inLab = (x: number, y: number, z: number) => gen.overmap.omtAt(Math.floor(x / CHUNK), Math.floor(y / CHUNK), z).special?.uid === sp.uid;
    // any floor tile of the surface parking lot
    let s: [number, number] | null = null;
    const park = cells.find((c) => c.z === 0 && c.id.includes('parking_blockC0'))!;
    for (let ly = 0; ly < CHUNK && !s; ly++) for (let lx = 0; lx < CHUNK && !s; lx++) if (map.passable(park.x * CHUNK + lx, park.y * CHUNK + ly, 0)) s = [park.x * CHUNK + lx, park.y * CHUNK + ly];
    const seen = new Set<string>();
    const q: [number, number, number][] = [[s![0], s![1], 0]];
    const zs = new Set<number>();
    while (q.length) {
      const [x, y, z] = q.pop()!;
      zs.add(z);
      const t = map.terAt(x, y, z);
      const next: [number, number, number][] = [[x + 1, y, z], [x - 1, y, z], [x, y + 1, z], [x, y - 1, z]];
      for (const dir of ['down', 'up'] as const) {
        if (!hasFlag(t, dir === 'down' ? 'GOES_DOWN' : 'GOES_UP')) continue;
        const d = stairDestination(game, x, y, z, dir);
        if (d) next.push([d.x, d.y, d.z]);
      }
      for (const [nx, ny, nz] of next) {
        const k = `${nx},${ny},${nz}`;
        if (seen.has(k) || !inLab(nx, ny, nz)) continue;
        const nt = map.terAt(nx, ny, nz);
        // doors (card readers / hacking / consoles / bashing open them) and climbable barriers
        if (!map.passable(nx, ny, nz) && !/door|gate/.test(nt.id) && !hasFlag(nt, 'CLIMBABLE') && !nt.open) continue;
        seen.add(k);
        q.push([nx, ny, nz]);
      }
    }
    for (let z = 0; z >= -6; z--) expect(zs.has(z), `reached z ${z}`).toBe(true);
  });

  it('lab floors hold lab terrain, loot and lab monsters', () => {
    const ter = new Map<string, number>();
    const items = new Set<string>();
    const spawns = new Set<string>();
    for (const c of cells.filter((e) => e.z < 0)) {
      const ch = map.chunk(c.x, c.y, c.z)! as Chunk;
      for (let i = 0; i < CHUNK * CHUNK; i++) {
        const id = map.terrain.get(ch.ter[i]).id;
        ter.set(id, (ter.get(id) ?? 0) + 1);
      }
      const flat = (it: any): string[] => [it.typeId ?? it.id, ...((it.contents ?? []) as any[]).flatMap(flat)];
      for (const l of ch.items.values()) for (const it of l) for (const id of flat(it)) items.add(id);
      for (const s of ch.spawns) spawns.add(s.id);
    }
    expect(ter.get('t_concrete_wall') ?? 0).toBeGreaterThan(500);
    expect([...ter.keys()].some((id) => id.startsWith('t_card_science'))).toBe(true);
    expect([...ter.keys()].some((id) => id.startsWith('t_door_metal_locked'))).toBe(true);
    // ID cards to get through the readers, mutagen / lab supplies
    expect([...items].some((id) => id.startsWith('id_science'))).toBe(true);
    expect([...items].some((id) => /mutagen|serum/.test(id))).toBe(true);
    expect(items.size).toBeGreaterThan(200);
    expect([...spawns].some((id) => /^GROUP_LAB_/.test(id))).toBe(true);
    expect([...spawns].some((id) => /turret|secubot|skitterbot|hack/.test(id))).toBe(true);
  });
});

describe("BN's classic lab (Lab special + lab_basement, Lua lab mapgen)", () => {
  const { map, gen, start } = world(1);
  const { sp, cells } = labCells(gen, CLASSIC_LAB_SPECIAL, { x: start.omx, y: start.omy });

  it('has a z0 lab_stairs bunker over a multi-level basement with a finale at the bottom', () => {
    expect(sp).toBeDefined();
    expect(Math.hypot(sp.x - start.omx, sp.y - start.omy)).toBeLessThan(45);
    expect(cells.find((c) => c.z === 0)?.id).toBe('lab_stairs');
    expect(gen.overmap.omtAt(sp.x, sp.y, -1).type).toBe('lab_core');
    const under = cells.filter((c) => c.z < 0);
    for (const c of under) expect(LAB_BASEMENT_TYPES as readonly string[]).toContain(c.id);
    const bottom = Math.min(...under.map((c) => c.z));
    expect(bottom).toBeLessThanOrEqual(-2);
    expect(under.some((c) => c.z === bottom && c.id === 'lab_finale')).toBe(true);
    // every level but the bottom has a staircase room over the next level's core
    for (let z = -1; z > bottom; z--) {
      const st = under.find((c) => c.z === z && c.id === 'lab_stairs')!;
      expect(st, `z ${z}`).toBeDefined();
      expect(gen.overmap.omtAt(st.x, st.y, z - 1).type).toBe('lab_core');
    }
  });

  it('draws the entrance bunker and JSON floor plans, with stairs connecting every level', () => {
    for (const c of cells) map.chunk(c.x, c.y, c.z);
    const game = { map } as unknown as Game;
    const entry = map.chunk(sp.x, sp.y, 0)!;
    expect(entry.omt?.source).toBe('builtin:lua:lab');
    const ids = (ch: Chunk) => Array.from(ch.ter).map((t) => map.terrain.get(t).id);
    expect(ids(entry)).toContain('t_card_science');
    expect(ids(entry).filter((t) => t === 't_stairs_down').length).toBe(2);
    let walls = 0, connected = 0, downs = 0;
    for (const c of cells.filter((e) => e.z < 0)) {
      const ch = map.chunk(c.x, c.y, c.z)!;
      expect(ch.omt?.source).toBe('builtin:lua:lab');
      walls += ids(ch).filter((t) => t === 't_concrete_wall').length;
      for (let i = 0; i < CHUNK * CHUNK; i++) {
        const x = c.x * CHUNK + (i % CHUNK), y = c.y * CHUNK + Math.floor(i / CHUNK);
        if (!hasFlag(map.terAt(x, y, c.z), 'GOES_DOWN') || hasFlag(map.terAt(x, y, c.z), 'SWIMMABLE')) continue;
        downs++;
        const d = stairDestination(game, x, y, c.z, 'down');
        if (d && hasFlag(map.terAt(d.x, d.y, d.z), 'GOES_UP')) connected++;
      }
    }
    expect(walls).toBeGreaterThan(100);
    expect(downs).toBeGreaterThan(0);
    expect(connected).toBe(downs);
  });
});

