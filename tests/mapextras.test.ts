// BN C++ map extras on rendered subway chunks (src/world/mapgen/mapextras.ts; BN
// src/mapgen/map_extras.cpp mx_portal, mx_casings). The region's subway table is narrowed to the
// one extra under test, with chance 1, so every chunk gets it.
import { describe, expect, it } from 'vitest';
import { Rng } from '../src/core/rng';
import { WorldGenerator } from '../src/world/worldgen';
import type { OmtInfo } from '../src/world/overmap/overmap';
import { LINE_E, LINE_W, oterId } from '../src/world/overmap/oter';
import { CHUNK } from '../src/world/coords';
import type { Chunk, GameMap } from '../src/world/map';
import type { WorldgenData } from '../src/world/worldgen_data';
import { MapBuffer } from '../src/world/mapgen/buffer';
import { lineTo, mxPortal, type MapExtraEnv } from '../src/world/mapgen/mapextras';
import { loadNodeData, makeMap } from '../tools/lib/node_data';

const { game, wg } = loadNodeData();
const T = wg.overmap.terrains;

/** wg with the subway extras table reduced to `fn` at chance 1. */
function only(fn: string): WorldgenData {
  return { ...wg, mapgen: { ...wg.mapgen, extras: { ...wg.mapgen.extras, subway: { chance: 1, values: [{ id: fn, w: 1, fn }] } } } };
}

/** A subway OMT at (10, 10, -2) in rock, generated by `data`; returns the chunk. */
function subway(seed: number, data: WorldgenData, genVersion?: number): { map: GameMap; gen: WorldGenerator; c: Chunk } {
  const map = makeMap(game, seed);
  const gen = new WorldGenerator(seed, data, game, genVersion);
  gen.stats.quiet = true;
  gen.overmap.omtAt = (x: number, y: number, z: number): OmtInfo => {
    const ref = x === 10 && y === 10 && z === -2 ? { type: 'subway', rot: 0, line: LINE_E | LINE_W } : z === 0 ? { type: 'field', rot: 0, line: -1 } : { type: 'empty_rock', rot: 0, line: -1 };
    return { ...ref, id: oterId(ref, T) };
  };
  map.generator = gen;
  return { map, gen, c: map.chunk(10, 10, -2)! };
}

const X = 10 * CHUNK, Y = 10 * CHUNK;
const local = (k: number): [number, number] => [k % CHUNK, Math.floor(k / CHUNK)];
const furnId = (map: GameMap, c: Chunk, k: number) => map.furniture.get(c.furn[k]).id;

describe('mx_portal', () => {
  it('a portal trap ringed with rock rubble, and 0-4 single nether creatures on rubble', () => {
    const counts = new Set<number>();
    for (let s = 1; s <= 40; s++) {
      const { map, gen, c } = subway(s, only('mx_portal'));
      expect([...gen.stats.unsupported.keys()]).toEqual([]);
      const portals = [...c.traps].filter(([, id]) => id === 'tr_portal');
      expect(portals.length, `seed ${s}`).toBe(1);
      const [px, py] = local(portals[0][0]);
      // Away from the edge, so its 3x3 fits.
      expect(px >= 1 && px <= 22 && py >= 1 && py <= 22).toBe(true);
      for (let dy = -1; dy <= 1; dy++)
        for (let dx = -1; dx <= 1; dx++) {
          const k = (py + dy) * CHUNK + px + dx;
          expect(furnId(map, c, k), `seed ${s} (${px + dx}, ${py + dy})`).toBe('f_rubble_rock');
          // make_rubble clears what blocks: rubble is walkable, so nothing solid stays under it.
          expect(map.terrain.get(c.ter[k]).move_cost).toBeGreaterThan(0);
        }
      const nether = c.spawns.filter((sp) => sp.id === 'GROUP_NETHER_PORTAL');
      counts.add(nether.length);
      for (const sp of nether) {
        expect(sp).toMatchObject({ kind: 'group', individual: true, z: -2 });
        expect(sp.x === X + px && sp.y === Y + py, 'never on the portal').toBe(false);
        expect(furnId(map, c, (sp.y - Y) * CHUNK + sp.x - X)).toBe('f_rubble_rock');
      }
    }
    // rng(0, 4) attempts
    expect([...counts].sort()).toEqual([0, 1, 2, 3, 4]);
  }, 30_000);

  it('the trap and the monster group are real data', () => {
    expect(game.misc.trap.tr_portal).toBeTruthy();
    expect(game.monsterGroups.GROUP_NETHER_PORTAL).toBeTruthy();
    expect(game.furniture.f_rubble_rock).toBeTruthy();
  });

  it('genVersion 2 worlds keep generating without it (reported, nothing placed)', () => {
    const { gen, c } = subway(3, only('mx_portal'), 2);
    expect([...gen.stats.unsupported.keys()]).toEqual(['map_extra_function mx_portal']);
    expect([...c.traps.values()]).not.toContain('tr_portal');
  });

  it('make_rubble on a wall: bashed down (or dirt), then rubble; NO_FLOOR tiles get none', () => {
    // Open air (NO_FLOOR) except a floor tile and a wall beside it: the portal lands on one of
    // the two (BN only asks for a floor and no trap; a wall gets knocked down by make_rubble).
    const floor = MapBuffer.idx(5, 5), wall = MapBuffer.idx(6, 5);
    const env: MapExtraEnv = {
      expandItems: () => [],
      terrainFlags: (id) => (id === 't_open_air' ? ['NO_FLOOR'] : []),
      passable: (b, i) => b.ter[i] !== 't_wall',
      terrainBash: (id) => (id === 't_wall' ? 't_floor' : undefined),
      furnitureBash: () => undefined,
      fieldMaxIntensity: () => 3,
    };
    for (let seed = 1; seed <= 10; seed++) {
      const b = new MapBuffer('t_open_air');
      b.ter[floor] = 't_floor';
      b.ter[wall] = 't_wall';
      expect(mxPortal(env, b, new Rng(seed))).toBe(true);
      const [k] = [...b.traps.keys()];
      expect([floor, wall]).toContain(k);
      expect(b.ter[wall]).toBe('t_floor');
      expect(b.furn.flatMap((f, i) => (f ? [[i, f]] : []))).toEqual([[floor, 'f_rubble_rock'], [wall, 'f_rubble_rock']]);
      for (const sp of b.spawns) expect([floor, wall].filter((i) => i !== k)).toContain(MapBuffer.idx(sp.x, sp.y));
    }
    // Nothing floored at all: no portal (BN returns false).
    expect(mxPortal(env, new MapBuffer('t_open_air'), new Rng(1))).toBe(false);
  });
});

describe('mx_casings', () => {
  const casing = (id: string) => /_casing$|_hull$|_case_base$/.test(id);
  it('spent casings from ammo_casings, trash, blood (stacking, at most 3) and sometimes a bloody rag', () => {
    let rags = 0, blood = 0, wide = 0, tight = 0;
    const groups = game.itemGroups as Record<string, { entries: { item?: string }[] }>;
    const pool = new Set([...groups.ammo_casings.entries, ...groups.map_extra_casings.entries].map((e) => e.item));
    for (let s = 1; s <= 60; s++) {
      const { gen, c } = subway(s, only('mx_casings'));
      expect([...gen.stats.unsupported.keys()]).toEqual([]);
      expect([...gen.stats.unknownIds.keys()], `seed ${s}`).toEqual([]);
      const tiles: [number, number][] = [];
      for (const [k, items] of c.items) {
        for (const it of items) expect(pool.has(it.typeId) || it.typeId === 'rag_bloody', `${it.typeId}`).toBe(true);
        if (items.some((it) => casing(it.typeId))) tiles.push(local(k));
        if (items.some((it) => it.typeId === 'rag_bloody')) rags++;
      }
      expect(tiles.length, `seed ${s}: casings somewhere`).toBeGreaterThan(0);
      for (const [, fl] of c.fields) for (const f of fl) {
        expect(f.type).toBe('fd_blood');
        expect(f.intensity).toBeGreaterThanOrEqual(1);
        expect(f.intensity).toBeLessThanOrEqual(3);
        blood++;
      }
      const span = Math.max(...tiles.map((t) => t[0])) - Math.min(...tiles.map((t) => t[0])) + Math.max(...tiles.map((t) => t[1])) - Math.min(...tiles.map((t) => t[1]));
      // A pile (radius 1-2) spans at most 8; the battlefield and the firing line run wider.
      if (span > 12) wide++;
      else if (span <= 8) tight++;
    }
    expect(rags).toBeGreaterThan(5);
    expect(blood).toBeGreaterThan(20);
    expect(wide).toBeGreaterThan(10);
    expect(tight).toBeGreaterThan(5);
  }, 30_000);
});

describe('line_to', () => {
  it('matches BN bresenham with t = 0: start excluded, end included', () => {
    expect(lineTo([0, 0], [3, 1])).toEqual([[1, 0], [2, 1], [3, 1]]);
    expect(lineTo([5, 5], [5, 5])).toEqual([[5, 5]]);
    expect(lineTo([2, 2], [0, 0])).toEqual([[1, 1], [0, 0]]);
    expect(lineTo([0, 0], [1, 3])).toEqual([[0, 1], [1, 2], [1, 3]]);
  });
});
