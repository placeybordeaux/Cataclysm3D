import { CHUNK, MAX_Z, MIN_Z } from './coords';
import type { GameMap } from './map';

// Generates map chunks ahead of need in the browser's idle time, so walking into new
// territory finds its chunks already there instead of running mapgen (1–20 ms per house,
// more for big specials) inside the frame that first touches them.
//
// A chunk can't be generated in pieces, so the budget is "start one only when the idle
// period has room left": requestIdleCallback's deadline tells us how much of the vsync gap
// is free. Anything the prefetcher hasn't reached yet is still generated synchronously by
// GameMap.chunk (the renderer / game ask for it), exactly as before — this is only a head
// start, and generation stays deterministic regardless of order.

export interface PrefetchStats {
  /** chunks generated by the prefetcher */
  prefetched: number;
  /** chunks generated synchronously by someone else (renderer, game) — hitch candidates */
  sync: number;
  /** slowest prefetched generation, ms */
  maxMs: number;
  queue: number;
}

export interface PrefetchOpts {
  /** chunks around the player (and around the predicted position) to keep generated */
  radius: number;
  /** z-levels relative to the player's */
  below: number;
  above: number;
  /** seconds of movement to look ahead */
  lookahead: number;
  /** only start a generation when at least this many ms of idle time remain */
  minIdleMs: number;
}

export class ChunkPrefetcher {
  readonly stats: PrefetchStats = { prefetched: 0, sync: 0, maxMs: 0, queue: 0 };
  opts: PrefetchOpts = { radius: 6, below: 2, above: 2, lookahead: 3, minIdleMs: 8 };
  enabled = true;
  private inPrefetch = false;
  private queue: [number, number, number][] = [];
  private queueFor = '';
  private lastPos: { x: number; y: number; t: number } | null = null;
  private vel = { x: 0, y: 0 };
  private running = false;

  constructor(private map: GameMap, private pos: () => { x: number; y: number; z: number }) {
    map.onChunkGenerated.push(() => {
      if (!this.inPrefetch) this.stats.sync++;
    });
  }

  start(): void {
    if (this.running) return;
    this.running = true;
    const ric: (cb: (d: { timeRemaining(): number }) => void) => void =
      typeof requestIdleCallback === 'function'
        ? (cb) => requestIdleCallback(cb, { timeout: 250 })
        : (cb) => setTimeout(() => cb({ timeRemaining: () => 10 }), 16);
    const loop = (d: { timeRemaining(): number }) => {
      if (!this.running) return;
      if (this.enabled) {
        // At most a few per idle period: a generation that overruns the gap drops a frame.
        for (let n = 0; n < 4 && d.timeRemaining() >= this.opts.minIdleMs; n++) if (!this.step()) break;
      }
      ric(loop);
    };
    ric(loop);
  }

  stop(): void {
    this.running = false;
  }

  /** Track velocity (call once per frame). */
  observe(now = performance.now()): void {
    const p = this.pos();
    const l = this.lastPos;
    if (l && now > l.t) {
      const dt = (now - l.t) / 1000;
      // Teleports aren't movement; smooth the rest so a single jitter doesn't swing the target.
      const vx = (p.x - l.x) / dt, vy = (p.y - l.y) / dt;
      if (Math.hypot(vx, vy) < 60) {
        const k = Math.min(1, dt * 4);
        this.vel.x += (vx - this.vel.x) * k;
        this.vel.y += (vy - this.vel.y) * k;
      } else this.vel = { x: 0, y: 0 };
    }
    this.lastPos = { x: p.x, y: p.y, t: now };
  }

  /** Generate the next missing chunk; false when there is nothing to do. */
  step(): boolean {
    const next = this.next();
    if (!next) return false;
    const [cx, cy, z] = next;
    const t0 = performance.now();
    this.inPrefetch = true;
    try {
      this.map.chunk(cx, cy, z);
    } finally {
      this.inPrefetch = false;
    }
    this.stats.prefetched++;
    this.stats.maxMs = Math.max(this.stats.maxMs, performance.now() - t0);
    return true;
  }

  /** Nearest missing chunk to the predicted position (ahead of the player), or null. */
  private next(): [number, number, number] | null {
    const p = this.pos();
    const o = this.opts;
    const ax = p.x + this.vel.x * o.lookahead, ay = p.y + this.vel.y * o.lookahead;
    const pcx = Math.floor(p.x / CHUNK), pcy = Math.floor(p.y / CHUNK);
    const acx = Math.floor(ax / CHUNK), acy = Math.floor(ay / CHUNK);
    const key = `${pcx},${pcy},${acx},${acy},${p.z}`;
    if (key !== this.queueFor) this.rebuild(pcx, pcy, acx, acy, p.z, key);
    while (this.queue.length) {
      const c = this.queue.pop()!;
      if (!this.map.hasChunk(c[0], c[1], c[2])) {
        this.stats.queue = this.queue.length;
        return c;
      }
    }
    this.stats.queue = 0;
    return null;
  }

  private rebuild(pcx: number, pcy: number, acx: number, acy: number, pz: number, key: string): void {
    this.queueFor = key;
    const o = this.opts, R = o.radius;
    const want = new Map<string, [number, number, number, number]>();
    const addAround = (ccx: number, ccy: number, bias: number) => {
      for (let dy = -R; dy <= R; dy++)
        for (let dx = -R; dx <= R; dx++) {
          if (dx * dx + dy * dy > (R + 0.5) * (R + 0.5)) continue;
          for (let z = Math.max(MIN_Z, pz - o.below); z <= Math.min(MAX_Z, pz + o.above); z++) {
            const cx = ccx + dx, cy = ccy + dy;
            if (this.map.hasChunk(cx, cy, z)) continue;
            // Priority: distance from the player, pulled toward the direction of travel;
            // the player's own level first, then the ones next to it.
            const dp = Math.hypot(cx - pcx, cy - pcy), da = Math.hypot(cx - acx, cy - acy);
            const score = Math.min(dp, da * 0.75 + bias) + Math.abs(z - pz) * 1.5;
            const k = `${cx},${cy},${z}`;
            const prev = want.get(k);
            if (!prev || prev[3] > score) want.set(k, [cx, cy, z, score]);
          }
        }
    };
    addAround(pcx, pcy, 0);
    if (acx !== pcx || acy !== pcy) addAround(acx, acy, 0.5);
    // Popped from the end: sort descending.
    this.queue = [...want.values()].sort((a, b) => b[3] - a[3]).map(([x, y, z]) => [x, y, z]);
  }
}
