// Gates (gates.cpp open_gate) and climbing (iexamine::chainfence)

export interface GateDef {
  door: string;
  floor: string;
  walls?: string[];
  messages?: { pull?: string; open?: string; close?: string; fail?: string };
  moves?: number;
}

export function gateAt(game: Game, x: number, y: number, z: number): GateDef | null {
  const t = game.map.terAt(x, y, z);
  return (game.data.misc.gate?.[t.id] as GateDef | undefined) ?? null;
}

const FOUR: [number, number][] = [[0, -1], [1, 0], [0, 1], [-1, 0]];
const GATE_MAX = 24;

/** Toggle the gate controlled from (x, y, z). Returns 'open' | 'close' | 'fail' | 'nothing'. */
export function toggleGate(game: Game, x: number, y: number, z: number, gate: GateDef): 'open' | 'close' | 'fail' | 'nothing' {
  const map = game.map;
  const suitable = (tx: number, ty: number) => {
    const t = map.terAt(tx, ty, z);
    return gate.walls?.length ? gate.walls.includes(t.id) : hasFlag(t, 'WALL');
  };
  let open = false, close = false, fail = false;
  for (const [wx, wy] of FOUR) {
    const ax = x + wx, ay = y + wy;
    if (!suitable(ax, ay)) continue;
    for (const [gx, gy] of FOUR) {
      const sx = ax + gx, sy = ay + gy;
      if (sx === x && sy === y) continue;
      if (!open) {
        let cx = sx, cy = sy;
        // (bounded: gates are a few tiles wide; an open field of gate floor must not run away)
        for (let n = 0; n < GATE_MAX && map.terAt(cx, cy, z).id === gate.floor; n++) {
          const blocked = (game.player.tileX === cx && game.player.tileY === cy && game.player.z === z) || !!monstersOf(game)?.monsterAt(cx, cy, z);
          if (blocked) fail = true;
          else {
            map.setTer(cx, cy, z, gate.door);
            close = !fail;
          }
          cx += gx;
          cy += gy;
        }
      }
      if (!close) {
        let cx = sx, cy = sy;
        for (let n = 0; n < GATE_MAX; n++) {
          const id = map.terAt(cx, cy, z).id;
          if (id === gate.door) {
            map.setTer(cx, cy, z, gate.floor);
            open = !fail;
          } else if (id !== gate.floor) break;
          cx += gx;
          cy += gy;
        }
      }
    }
  }
  const msg = open ? gate.messages?.open ?? 'The gate is opened!' : close ? gate.messages?.close ?? 'The gate is closed!' : fail ? gate.messages?.fail ?? "The gate can't be closed!" : 'Nothing happens.';
  game.message(msg);
  if (open || close) game.events.emit('mapChanged', { x, y, z });
  return open ? 'open' : close ? 'close' : fail ? 'fail' : 'nothing';
}

export function operateGate(game: Game, x: number, y: number, z: number): boolean {
  const gate = gateAt(game, x, y, z);
  if (!gate) {
    game.message('Nothing happens.');
    return false;
  }
  game.message(gate.messages?.pull ?? 'You turn the handle…');
  return game.activities.start({
    name: 'operating the gate',
    duration: Math.max(1, Math.round((gate.moves ?? 1800) / 100)),
    onComplete: () => void toggleGate(game, x, y, z, gate),
  });
}

/** Where climbing over the obstacle at (x, y) puts you: the tile beyond it, away from you. */
export function climbTarget(game: Game, x: number, y: number, z: number): { x: number; y: number } | null {
  const p = game.player;
  const dx = Math.sign(x - p.tileX), dy = Math.sign(y - p.tileY);
  if (!dx && !dy) return null;
  const cands: [number, number][] = [[x + dx, y + dy]];
  if (dx && dy) cands.push([x + dx, y], [x, y + dy]);
  for (const [tx, ty] of cands) if (game.map.passable(tx, ty, z) && !monstersOf(game)?.monsterAt(tx, ty, z)) return { x: tx, y: ty };
  return null;
}

/** iexamine::chainfence: vault/climb over a CLIMBABLE obstacle. */
export function climbOver(game: Game, x: number, y: number, z: number): string | null {
  const p = game.player;
  const t = game.map.terAt(x, y, z);
  const dest = climbTarget(game, x, y, z);
  if (!dest) return `There's no room to climb over the ${t.name}.`;
  const simple = hasFlag(t, 'CLIMB_SIMPLE');
  game.message(simple ? 'You vault over the obstacle.' : `You climb over the ${t.name}.`);
  p.x = dest.x + 0.5;
  p.y = dest.y + 0.5;
  p.burnMoveStamina?.(simple ? 300 : 400);
  emitSound(game, { x, y, z }, simple ? 4 : 8, 'rattle', { category: 'movement' as never, source: p, sfxId: '' });
  return null;
}

