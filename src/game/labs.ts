export interface ComputerOption {
  name: string;
  action: string;
  security?: number;
}
export interface ComputerData {
  name?: string;
  access_denied?: string;
  security?: number;
  options?: ComputerOption[];
  failures?: { action: string }[];
  /** runtime state, persisted on the chunk */
  alerts?: number;
  next_attempt?: number;
}

/** The computer stored by mapgen at the console tile (chunk.computers), if any. */
export function computerAt(game: Game, x: number, y: number, z: number): ComputerData | null {
  const c = game.map.chunk(chunkOf(x), chunkOf(y), z);
  return (c?.computers.get(localOf(y) * CHUNK + localOf(x)) as ComputerData | undefined) ?? null;
}

/** BN terrain or compatible furniture with CONSOLE and stored computer data. */
export function isConsole(game: Game, x: number, y: number, z: number): boolean {
  const f = game.map.furnAt(x, y, z);
  return (hasFlag(f, 'CONSOLE') || hasFlag(game.map.terAt(x, y, z), 'CONSOLE')) && !!computerAt(game, x, y, z);
}

/** Actions this port implements (anything else shows as UNAVAILABLE, like can_activate). */
export const COMPUTER_ACTIONS = new Set([
  'open', 'open_disarm', 'unlock', 'unlock_disarm', 'release', 'release_bionics', 'release_disarm', 'research', 'maps',
  'map_sewer', 'map_subway', 'list_bionics', 'list_mutations', 'shutters', 'elevator_on', 'lock', 'terminate', 'toll',
]);

function markChanged(game: Game, x: number, y: number, z: number): void {
  const c = game.map.chunk(chunkOf(x), chunkOf(y), z);
  if (c) c.version++;
}

/** computer_session::hack_attempt: Nd6 (computer skill, int adjusted) vs (security + 2·alerts)d6. */
export function computerHackAttempt(game: Game, comp: ComputerData, security = comp.security ?? 0): boolean {
  const p = game.player;
  const rng = p.rng;
  const skill = Math.round(p.getSkill('computer'));
  security += (comp.alerts ?? 0) * 2;
  let roll = skill;
  if (p.int < 8 && rng.oneIn(2)) roll -= rng.int(0, 8 - p.int);
  else if (p.int > 8 && rng.oneIn(3)) roll += rng.int(0, p.int - 8);
  const ok = rng.dice(Math.max(0, roll), 6) >= rng.dice(Math.max(0, security), 6);
  p.practice('computer', ok ? 15 + security * 3 : 7);
  return ok;
}

/** A computer failure (computer_session::activate_failure). */
export async function computerFailure(game: Game, x: number, y: number, z: number, action: string, ui: LabUi): Promise<void> {
  const p = game.player;
  const sys = monstersOf(game);
  switch (action) {
    case 'shutdown': {
      const breakConsole = (tx: number, ty: number): boolean => {
        if (!hasFlag(game.map.terAt(tx, ty, z), 'CONSOLE') && !hasFlag(game.map.furnAt(tx, ty, z), 'CONSOLE')) return false;
        const furniture = game.map.furnAt(tx, ty, z);
        if (hasFlag(furniture, 'CONSOLE')) {
          const broken = furniture.id.replace('console', 'console_broken');
          game.map.setFurn(tx, ty, z, game.map.furniture.has(broken) ? broken : 'f_null');
        }
        game.map.setTer(tx, ty, z, 't_console_broken');
        game.events.emit('mapChanged', { x: tx, y: ty, z });
        return true;
      };
      let found = false;
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
        if (breakConsole(p.tileX + dx, p.tileY + dy)) found = true;
      }
      if (!found) for (const chunk of game.map.loadedChunks()) {
        if (chunk.z !== z) continue;
        for (let by = 0; by < CHUNK; by++) for (let bx = 0; bx < CHUNK; bx++) breakConsole(chunk.cx * CHUNK + bx, chunk.cy * CHUNK + by);
      }
      game.message('The console shuts down.', 'c_red');
      break;
    }
    case 'alarm':
      emitSound(game, { x: p.tileX, y: p.tileY, z }, 60, 'an alarm sound!', { category: 'alarm' as never, source: p });
      labHooks.onAlarm?.(x, y, z);
      break;
    case 'manhacks': {
      const n = p.rng.int(4, 8);
      let placed = 0;
      for (let i = 0; i < n; i++) if (placeNear(game, 'mon_manhack', p.tileX, p.tileY, z, 3)) placed++;
      if (placed) game.message('Manhacks drop from compartments in the ceiling.', 'c_yellow');
      break;
    }
    case 'secubots':
      if (placeNear(game, 'mon_secubot', p.tileX, p.tileY, z, 3)) game.message('A secubot emerges from a compartment in the floor.', 'c_yellow');
      break;
    case 'damage': {
      game.message('The console shocks you.');
      game.message('Your body is damaged by the electric shock!', 'c_red');
      const dmg = p.rng.int(1, 10);
      for (const bp of ['torso', 'head', 'arm_l', 'arm_r', 'leg_l', 'leg_r'] as const) p.takeHit(bp, [{ type: 'electric', amount: dmg }]);
      break;
    }
    default:
      await ui.show('Error', 'Maximum login attempts exceeded.');
  }
  void sys;
}

function placeNear(game: Game, id: string, x: number, y: number, z: number, r: number): boolean {
  const sys = monstersOf(game);
  if (!sys) return false;
  for (let tries = 0; tries < 30; tries++) {
    const tx = x + game.player.rng.int(-r, r), ty = y + game.player.rng.int(-r, r);
    if ((tx === x && ty === y) || !game.map.passable(tx, ty, z) || sys.monsterAt(tx, ty, z)) continue;
    return !!sys.spawnById(id, tx + 0.5, ty + 0.5, z);
  }
  return false;
}

async function randomFailure(game: Game, x: number, y: number, z: number, comp: ComputerData, ui: LabUi): Promise<void> {
  const f = comp.failures ?? [];
  if (!f.length) return ui.show(comp.name ?? 'Computer', 'Maximum login attempts exceeded.  Press any key…');
  await computerFailure(game, x, y, z, f[game.player.rng.int(0, f.length - 1)].action, ui);
}

/** Run one computer action. Returns the text shown on the terminal. */
export function computerAction(game: Game, x: number, y: number, z: number, comp: ComputerData, action: string): string {
  const p = game.player;
  const px = p.tileX, py = p.tileY;
  switch (action) {
    case 'open':
    case 'unlock':
      translateRadius(game, 't_door_metal_locked', 't_door_metal_c', 8, px, py, z);
      return action === 'open' ? 'Doors opened.  Press any key…' : 'Lock disabled.  Press any key…';
    case 'open_disarm':
    case 'unlock_disarm':
      despawnInOmt(game, x, y, z, 'CONSOLE_DESPAWN');
      translateRadius(game, 't_door_metal_locked', 't_door_metal_c', 8, px, py, z);
      return 'Lock disabled.  Press any key…';
    case 'lock':
      translateRadius(game, 't_door_metal_c', 't_door_metal_locked', 8, px, py, z);
      return 'Door locked.  Press any key…';
    case 'release':
    case 'release_bionics':
    case 'release_disarm': {
      if (action === 'release_disarm') despawnInOmt(game, x, y, z, 'CONSOLE_DESPAWN');
      emitSound(game, { x: px, y: py, z }, 40, 'an alarm sound!', { category: 'alarm' as never, source: p });
      translateRadius(game, 't_reinforced_glass_lab', 't_thconc_floor', action === 'release' ? 25 : 3, px, py, z);
      return 'Containment shields opened.  Press any key…';
    }
    case 'terminate': {
      const sys = monstersOf(game);
      let n = 0;
      for (const m of [...(sys?.all ?? [])]) {
        if (m.dead || m.z !== z || !sameOmt(Math.floor(m.x), Math.floor(m.y), x, y)) continue;
        const t = game.map.terAt(Math.floor(m.x), Math.floor(m.y), z).id;
        if (t === 't_thconc_floor' || t === 't_reinforced_glass_lab') continue;
        void n++;
      }
      return 'Subjects terminated.  Press any key…';
    }
    case 'research': {
      const seed = (chunkOf(x) * 73856093) ^ (chunkOf(y) * 19349663) ^ (z * 83492791) ^ ((comp.alerts ?? 0) * 7919);
      const rng = new (p.rng.constructor as new (s: number) => { next(): number; int(a: number, b: number): number })(seed);
      const log = snippet(game.data, 'lab_notes', rng as never) ?? 'No data found.';
      comp.alerts = (comp.alerts ?? 0) + 1;
      return `${log}\n\n${comp.alerts === 1 ? 'Local data-access error logged, alerting helpdesk.  Press any key…' : 'Warning: anomalous archive-access activity detected at this node.  Press any key…'}`;
    }
    case 'maps':
    case 'map_sewer':
    case 'map_subway': {
      const cx = chunkOf(px), cy = chunkOf(py);
      const r = action === 'maps' ? 40 : 20;
      for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx++) game.overmapSeen.add(`${cx + dx},${cy + dy},0`);
      comp.options = (comp.options ?? []).filter((o) => o.action !== action);
      comp.alerts = (comp.alerts ?? 0) + (action === 'maps' ? 1 : 0);
      return action === 'maps' ? 'Surface map data downloaded.  Local anomalous-access error logged.  Press any key…' : 'Map data downloaded.  Press any key…';
    }
    case 'list_bionics':
    case 'list_mutations': {
      const names: string[] = [];
      const want = action === 'list_bionics' ? (it: Item) => !!it.def.flags?.includes('CBM') : (it: Item) => /mutagen|serum/.test(it.typeId);
      const cx0 = chunkOf(x) * CHUNK, cy0 = chunkOf(y) * CHUNK;
      for (let ty = cy0 - CHUNK; ty < cy0 + 2 * CHUNK; ty++)
        for (let tx = cx0 - CHUNK; tx < cx0 + 2 * CHUNK; tx++)
          for (const it of game.map.itemsAt(tx, ty, z) as Item[]) for (const i of [it, ...(it.allContents?.() ?? [])]) if (want(i)) names.push(i.name());
      return `${action === 'list_bionics' ? 'Bionic access - Manifest:' : 'Mutagen & Serum - Manifest:'}\n\n${names.slice(0, 20).join('\n') || 'None.'}${names.length > 20 ? `\n${names.length - 20} OTHERS FOUND…` : ''}`;
    }
    case 'shutters':
      translateRadius(game, 't_reinforced_glass_shutter_open', 't_reinforced_glass_shutter', 8, px, py, z, true);
      return 'Toggling shutters.  Press any key…';
    case 'elevator_on':
      for (let ty = chunkOf(py) * CHUNK - CHUNK; ty < chunkOf(py) * CHUNK + 2 * CHUNK; ty++)
        for (let tx = chunkOf(px) * CHUNK - CHUNK; tx < chunkOf(px) * CHUNK + 2 * CHUNK; tx++)
          if (game.map.terAt(tx, ty, z).id === 't_elevator_control_off') game.map.setTer(tx, ty, z, 't_elevator_control');
      return 'Elevator activated.  Press any key…';
    case 'toll':
      emitSound(game, { x: px, y: py, z }, 120, 'Bohm…  Bohm…  Bohm…', { source: p });
      return '[Bellsystem 1.2] activated.  Have a nice day.';
    default:
      return 'ERROR: function unavailable.';
  }
}

/** computer_session::use — the whole login + root menu loop. */
export async function useComputer(game: Game, x: number, y: number, z: number, ui: LabUi): Promise<void> {
  const comp = computerAt(game, x, y, z);
  if (!comp) return;
  const name = comp.name ?? 'Computer';
  if ((comp.security ?? 0) > 0) {
    if ((comp.next_attempt ?? 0) > game.clock.seconds) {
      await ui.show(name, 'Access is temporary blocked for security purposes.\nPlease contact the system administrator.');
      return;
    }
    await ui.show(name, `Logging into ${name}…\n\n${comp.access_denied ?? 'ERROR!  Access denied!'}`);
    if (!(await ui.ask('Bypass security?'))) return;
    if (!computerHackAttempt(game, comp)) {
      await randomFailure(game, x, y, z, comp, ui);
      markChanged(game, x, y, z);
      return;
    }
    comp.security = 0;
    markChanged(game, x, y, z);
    await ui.show(name, 'Login successful.  Press any key…');
  }
  for (;;) {
    if (!isConsole(game, x, y, z)) return;
    const opts = comp.options ?? [];
    const i = await ui.choose(`${name} - Root Menu`, opts.map((o) => ({ label: COMPUTER_ACTIONS.has(o.action) ? o.name : `${o.name} (UNAVAILABLE)`, disabled: !COMPUTER_ACTIONS.has(o.action) })));
    if (i < 0 || i >= opts.length) return;
    const o = opts[i];
    if ((o.security ?? 0) + (comp.alerts ?? 0) > 0) {
      if (!(await ui.ask('Password required.  Hack into system?'))) continue;
      if (!computerHackAttempt(game, comp, o.security ?? 0)) {
        await randomFailure(game, x, y, z, comp, ui);
        markChanged(game, x, y, z);
        return;
      }
      o.security = 0;
    }
    const text = computerAction(game, x, y, z, comp, o.action);
    markChanged(game, x, y, z);
    await ui.show(name, text);
  }
}

