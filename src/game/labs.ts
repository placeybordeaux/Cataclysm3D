// Elevators (iexamine::elevator)

/** CDDA point::rotate within an OMT (24x24): turns clockwise. */
function rotateLocal(lx: number, ly: number, turns: number): [number, number] {
  turns = ((turns % 4) + 4) % 4;
  for (let t = 0; t < turns; t++) [lx, ly] = [CHUNK - 1 - ly, lx];
  return [lx, ly];
}

/** Floors an elevator control at (x, y, z) serves: z levels where the same (rotated) spot is a powered control. */
export function elevatorFloors(game: Game, x: number, y: number, z: number, hooks: LabHooks = labHooks): { z: number; x: number; y: number; name: string }[] {
  const out: { z: number; x: number; y: number; name: string }[] = [];
  const cx = chunkOf(x), cy = chunkOf(y);
  const rotHere = hooks.omtRotation?.(cx, cy, z) ?? 0;
  // from the highest populated level (GameMap.topZ), not MAX_Z: reading a level runs its
  // mapgen, and open air up to z10 would raise topZ for every sky-cover loop. A tower's levels
  // are generated with its column whenever you stand at its foot.
  for (let tz = Math.min(MAX_Z, game.map.topZ()); tz >= MIN_Z; tz--) {
    const rot = (((hooks.omtRotation?.(cx, cy, tz) ?? 0) - rotHere) % 4 + 4) % 4;
    const [lx, ly] = rotateLocal(localOf(x), localOf(y), rot);
    const tx = cx * CHUNK + lx, ty = cy * CHUNK + ly;
    if (game.map.terAt(tx, ty, tz).examine_action === 'elevator') out.push({ z: tz, x: tx, y: ty, name: hooks.omtName?.(cx, cy, tz) ?? '' });
  }
  return out;
}

/** Ride the elevator whose control is at (x, y, z) to floor `toZ`. Returns a refusal or null. */
export function rideElevator(game: Game, x: number, y: number, z: number, toZ: number, hooks: LabHooks = labHooks): string | null {
  const p = game.player;
  // this_elevator: ELEVATOR tiles within SEEX-1 of the control
  const cab: [number, number][] = [];
  for (let dy = -11; dy <= 11; dy++)
    for (let dx = -11; dx <= 11; dx++) if (hasFlag(game.map.terAt(x + dx, y + dy, z), 'ELEVATOR')) cab.push([x + dx, y + dy]);
  if (!cab.some(([tx, ty]) => tx === p.tileX && ty === p.tileY)) return 'You must stand inside the elevator to use it.';
  if (toZ === z) return null;
  const cx = chunkOf(x), cy = chunkOf(y);
  const rot = ((((hooks.omtRotation?.(cx, cy, toZ) ?? 0) - (hooks.omtRotation?.(cx, cy, z) ?? 0)) % 4) + 4) % 4;
  const dest = (tx: number, ty: number): [number, number] => {
    // positions outside this OMT (a cab straddling the border) keep their offset
    if (chunkOf(tx) !== cx || chunkOf(ty) !== cy) return [tx, ty];
    const [lx, ly] = rotateLocal(localOf(tx), localOf(ty), rot);
    return [cx * CHUNK + lx, cy * CHUNK + ly];
  };
  const map = game.map;
  for (const [tx, ty] of cab) {
    const [dx, dy] = dest(tx, ty);
    for (const it of [...map.itemsAt(tx, ty, z)] as Item[]) moveItem(it, L.ground(map, tx, ty, z), L.ground(map, dx, dy, toZ), { force: true, quiet: true });
  }
  const sys = monstersOf(game);
  for (const m of sys?.all ?? []) {
    if (m.dead || m.z !== z) continue;
    if (!cab.some(([tx, ty]) => tx === Math.floor(m.x) && ty === Math.floor(m.y))) continue;
    const [dx, dy] = dest(Math.floor(m.x), Math.floor(m.y));
    m.x = dx + 0.5;
    m.y = dy + 0.5;
    m.z = toZ;
  }
  const [px, py] = dest(p.tileX, p.tileY);
  p.x = px + (p.x - Math.floor(p.x));
  p.y = py + (p.y - Math.floor(p.y));
  p.z = toZ;
  // Keeping the sub-tile offset across the rotation can land it inside a wall on the other
  // floor even though the cab's own footprint is clear (same class of bug as a fall carrying
  // its fractional x/y onto a different layout below — src/game/zlevels.ts fallIfUnsupported).
  [p.x, p.y] = resolveOverlap(game.map, p.x, p.y, toZ);
  game.message(`The elevator ${toZ < z ? 'descends' : 'ascends'} to level ${toZ}.`);
  emitSound(game, { x: px, y: py, z: toZ }, 8, 'a mechanical hum', { source: p });
  return null;
}

