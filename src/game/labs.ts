// Hacking card readers (hacking_activity_actor)

export function hackTool(game: Game): Item | null {
  const tools = game.player.inv.findByQuality('HACK', 1);
  tools.sort((a, b) => b.qualityLevel('HACK') - a.qualityLevel('HACK'));
  return tools[0] ?? null;
}

const chargesPerUse = (it: Item) => Math.max(0, Number((it.def as { charges_per_use?: number }).charges_per_use ?? 0));

/** iexamine::can_hack: a HACK tool with enough charges (and the survivor can read). */
export function canHack(game: Game, say: boolean): boolean {
  const p = game.player;
  if (p.hasTrait('ILLITERATE')) {
    if (say) game.message('You cannot read!');
    return false;
  }
  const t = hackTool(game);
  if (!t || t.ammoRemaining() < chargesPerUse(t)) {
    if (say && t) game.message("You don't have a hacking tool with enough charges!");
    return false;
  }
  return true;
}

/** hack_level: computer skill + (tool HACK quality - 2) + int/2 - 8. */
export function hackLevel(game: Game, tool: Item): number {
  const p = game.player;
  return Math.round(p.getSkill('computer') + (tool.qualityLevel('HACK') - 2) + p.int / 2 - 8);
}

export type HackResult = 'fail' | 'nothing' | 'success';

/** hack_attempt: ceil(normal_roll(level, 5)) < 0 short circuit + alarm, < 6 nothing, else success. */
export function hackRoll(game: Game, tool: Item): HackResult {
  const p = game.player;
  p.practice('computer', 20);
  const success = Math.ceil(normalRoll(p.rng, hackLevel(game, tool), 5));
  if (success < 0) {
    game.message('You cause a short circuit!', 'c_red');
    tool.ammoConsume(chargesPerUse(tool) * (success <= -5 ? 3 : 1));
    return 'fail';
  }
  return success < 6 ? 'nothing' : 'success';
}

function normalRoll(rng: { next(): number }, mean: number, sd: number): number {
  const u = Math.max(1e-9, rng.next()), v = rng.next();
  return mean + sd * Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

/** Finish a hack on a card reader at (x, y, z) (hacking_activity_actor::finish, DOOR type). */
export function finishHack(game: Game, x: number, y: number, z: number, tool: Item): HackResult {
  const r = hackRoll(game, tool);
  if (r === 'fail') {
    emitSound(game, { x: game.player.tileX, y: game.player.tileY, z }, 60, 'an alarm sound!', { category: 'alarm' as never, source: game.player });
    labHooks.onAlarm?.(x, y, z);
  } else if (r === 'nothing') game.message('You fail the hack, but no alarms are triggered.');
  else {
    game.message('You activate the panel!');
    game.message('The nearby doors unlock.', 'c_light_green');
    if (game.map.terrain.has('t_card_reader_broken')) game.map.setTer(x, y, z, 't_card_reader_broken');
    translateRadius(game, 't_door_metal_locked', 't_door_metal_c', 3, x, y, z);
  }
  return r;
}

export function startHacking(game: Game, x: number, y: number, z: number): boolean {
  const tool = hackTool(game);
  if (!tool || !canHack(game, true)) return false;
  tool.ammoConsume(chargesPerUse(tool));
  return game.activities.start({
    name: 'hacking',
    duration: 300,
    onComplete: () => void finishHack(game, x, y, z, tool),
  });
}

