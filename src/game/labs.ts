// Card readers (cardreader_examine_actor)

export interface CardreaderDef {
  type: 'cardreader';
  flags: string[];
  card_ids?: string[];
  connected_doors?: boolean;
  consume_card?: boolean;
  allow_hacking?: boolean;
  despawn_monsters?: boolean;
  radius?: number;
  terrain_changes?: Record<string, string>;
  furn_changes?: Record<string, string>;
  mapgen_id?: string;
  query_msg?: string;
  success_msg?: string;
  redundant_msg?: string;
}

export function cardreaderOf(t: TerrainDef): CardreaderDef | null {
  const e = t.examine_action as CardreaderDef | string | undefined;
  if (e === 'cardreader') {
    const id = t.id === 't_card_science' ? 'id_science' : t.id === 't_card_military' ? 'id_military' : 'id_industrial';
    return { type: 'cardreader', flags: [], card_ids: [id], connected_doors: true, radius: 3, terrain_changes: { t_door_metal_locked: 't_door_metal_c' } };
  }
  return e && typeof e === 'object' && e.type === 'cardreader' ? e : null;
}

/** Cards the survivor carries that this reader accepts (any of its flags). */
export function cardsFor(game: Game, def: CardreaderDef): Item[] {
  return game.player.inv.allItems().filter((it) => def.card_ids?.includes(it.typeId) || def.flags.some((f) => it.hasFlag(f)));
}

/** cardreader_examine_actor::apply: open what the reader controls. True if anything changed. */
export function applyCardreader(game: Game, x: number, y: number, z: number, def: CardreaderDef, hooks: LabHooks = labHooks): boolean {
  if (def.mapgen_id) {
    return !!hooks.mapgenUpdate?.(def.mapgen_id, chunkOf(x), chunkOf(y), z);
  }
  let open = false;
  const r = def.radius ?? 3;
  for (let dy = -r; dy <= r; dy++)
    for (let dx = -r; dx <= r; dx++) {
      const tx = x + dx, ty = y + dy;
      if (!game.map.hasChunk(chunkOf(tx), chunkOf(ty), z)) continue;
      const t = game.map.terAt(tx, ty, z), f = game.map.furnAt(tx, ty, z);
      const nt = def.terrain_changes?.[t.id];
      if (nt && game.map.terrain.has(nt)) {
        const queue: [number, number][] = [[tx, ty]];
        const seen = new Set<string>();
        for (let i = 0; i < queue.length; i++) {
          const [ax, ay] = queue[i];
          const key = `${ax},${ay}`;
          if (seen.has(key) || !game.map.hasChunk(chunkOf(ax), chunkOf(ay), z)) continue;
          seen.add(key);
          if (game.map.terAt(ax, ay, z).id !== t.id) continue;
          game.map.setTer(ax, ay, z, nt);
          game.events.emit('mapChanged', { x: ax, y: ay, z });
          open = true;
          if (def.connected_doors) queue.push([ax + 1, ay], [ax - 1, ay], [ax, ay + 1], [ax, ay - 1]);
        }
      }
      const nf = def.furn_changes?.[f.id];
      if (nf && game.map.furniture.has(nf)) {
        game.map.setFurn(tx, ty, z, nf);
        open = true;
      }
    }
  return open;
}

/** Swipe a card: iexamine cardreader_examine_actor::call. Returns what happened. */
export async function useCardreader(game: Game, x: number, y: number, z: number, def: CardreaderDef, ui: LabUi): Promise<'opened' | 'redundant' | 'hacking' | 'none'> {
  const cards = cardsFor(game, def);
  if (cards.length && (await ui.ask(def.query_msg ?? 'Swipe your ID card?'))) {
    const open = applyCardreader(game, x, y, z, def);
    if (def.despawn_monsters !== false) despawnInOmt(game, x, y, z, 'ID_CARD_DESPAWN');
    if (open) {
      game.message(stripTags(def.success_msg ?? 'The nearby doors unlock.'), 'c_light_green');
      if (def.consume_card !== false) removeItem(game, cards[0]);
      return 'opened';
    }
    game.message(def.redundant_msg ?? 'The nearby doors are already opened.');
    return 'redundant';
  }
  if (def.allow_hacking !== false && canHack(game, true) && (await ui.ask('Attempt to hack this card-reader?'))) {
    return startHacking(game, x, y, z) ? 'hacking' : 'none';
  }
  if (def.allow_hacking === false && canHack(game, false)) game.message('This card-reader cannot be hacked.');
  else if (!cards.length) game.message('You need a matching ID card to use this.');
  return 'none';
}

const stripTags = (s: string) => s.replace(/<\/?[a-z_]+>/g, '');

/** A keycard is used up (consume_card). */
function removeItem(game: Game, it: Item): void {
  const loc = game.player.inv.locOf(it);
  if (loc) consumeItem(it, loc, it.countByCharges ? 1 : undefined);
}

