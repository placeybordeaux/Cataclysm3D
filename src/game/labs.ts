export interface LabUi {
  /** CDDA query_yn */
  ask(question: string): Promise<boolean>;
  /** CDDA uilist; resolves the chosen index or -1 */
  choose(title: string, options: { label: string; disabled?: boolean }[]): Promise<number>;
  /** Terminal output (a computer screen / popup); resolves when dismissed */
  show(title: string, text: string): Promise<void>;
}

/**
 * Headless UI for tests/automation: answers yes, picks `picks` in order (default: the first
 * enabled entry once, then cancels), logs terminal text.
 */
export const autoUi = (game: Game, picks?: number[]): LabUi => {
  let n = 0;
  return {
    ask: async () => true,
    choose: async (_t, o) => (picks ? picks[n++] ?? -1 : n++ === 0 ? o.findIndex((e) => !e.disabled) : -1),
    show: async (_t, text) => game.message(text),
  };
};

const monstersOf = (game: Game) => (game as unknown as { monsters?: { all: Monster[]; remove(m: Monster): void; dropStuck(m: Monster): void; spawnById(id: string, x: number, y: number, z: number): Monster | null; monsterAt(x: number, y: number, z: number): Monster | null } }).monsters;

const sameOmt = (ax: number, ay: number, bx: number, by: number) => chunkOf(ax) === chunkOf(bx) && chunkOf(ay) === chunkOf(by);

/** Remove hostile monsters with `flag` in the OMT of (x, y, z) (card readers: ID_CARD_DESPAWN). */
export function despawnInOmt(game: Game, x: number, y: number, z: number, flag: string): number {
  const sys = monstersOf(game);
  if (!sys) return 0;
  let n = 0;
  for (const m of [...sys.all]) {
    if (m.dead || m.z !== z || !sameOmt(Math.floor(m.x), Math.floor(m.y), x, y)) continue;
    if (!m.type.flags.includes(flag) || m.friendly) continue;
    sys.dropStuck(m); // arrows stuck in it stay behind
    sys.remove(m);
    n++;
  }
  return n;
}

/** map::translate_radius: every `from` tile within `radius` becomes `to` (same z). */
export function translateRadius(game: Game, from: string, to: string, radius: number, x: number, y: number, z: number, toggle = false): number {
  let n = 0;
  const r = Math.ceil(radius);
  const changes: [number, number, string][] = [];
  for (let dy = -r; dy <= r; dy++)
    for (let dx = -r; dx <= r; dx++) {
      if (Math.hypot(dx, dy) > radius + 0.5) continue;
      const id = game.map.terAt(x + dx, y + dy, z).id;
      if (id === from) changes.push([x + dx, y + dy, to]);
      else if (toggle && id === to) changes.push([x + dx, y + dy, from]);
    }
  for (const [cx, cy, id] of changes) {
    game.map.setTer(cx, cy, z, id);
    game.events.emit('mapChanged', { x: cx, y: cy, z });
    n++;
  }
  return n;
}

