import type { Game } from './game';
import type { Chunk } from '../world/map';
import { CHUNK, chunkKey } from '../world/coords';
import { hasFlag } from '../world/registry';
import { DEFAULT_WEATHER_GEN, weatherPoint, climateSeconds } from './weather';
import { isOutside } from './vision';
import { restockFruits } from './harvest';
import { growPlant } from './farming';
import type { Item } from './item';
import { destroyWhere, L } from './moves';

// Lazy per-chunk world upkeep, like CDDA map::actualize: nothing is simulated for chunks you
// aren't near; when one comes into range again, everything that should have happened while
// you were away is applied at once from timestamps:
//   - HARVESTED bushes/trees regrow (map::restock_fruits) when the season changed,
//   - crops grow to the stage their seed's age calls for (map::grow_plant),
//   - food on the ground / in furniture rots by the hour-by-hour outdoor temperature
//     (indoors a little warmer; unpowered fridges and freezers are just cupboards).
// Food generated by mapgen ages from the start of the cataclysm like CDDA's item birthdays,
// so a fridge you open on day 40 holds rotten milk.

export interface ChunkStamp {
  /** last actualize (game seconds): restock_fruits compares seasons against it */
  touched: number;
  /** rot has been applied up to this time */
  rot: number;
}

export class Actualizer {
  readonly stamps = new Map<string, ChunkStamp>();
  /** Actualize chunks within this many chunks of the player. */
  radius = 3;
  /** Game seconds between sweeps around the player. */
  interval = 600;
  private acc = Infinity;
  private harvested = new Map<number, boolean>();
  /**
   * Save-system dirty tracking (set by nature.ts). A chunk the player never touched stays
   * "clean" through actualizing: rot of mapgen food is recomputed from day 0 if the chunk is
   * regenerated, so it doesn't need to be kept in memory or saved.
   */
  tracking: { isDirty(c: Chunk): boolean; rebaseline(c: Chunk): void } | null = null;
  private tempCache = new Map<number, number>();

  constructor(private game: Game) {}

  /** Outdoor temperature (°C) at the whole hour containing `t`. */
  private hourTemp(t: number): number {
    const h = Math.floor(t / 3600);
    let v = this.tempCache.get(h);
    if (v === undefined) {
      v = weatherPoint(this.game.seed, climateSeconds(h * 3600 + 1800)).temperature;
      if (this.tempCache.size > 20000) this.tempCache.clear();
      this.tempCache.set(h, v);
    }
    return v;
  }

  private isHarvested(ti: number): boolean {
    let v = this.harvested.get(ti);
    if (v === undefined) this.harvested.set(ti, (v = hasFlag(this.game.map.terrain.defs[ti], 'HARVESTED')));
    return v;
  }

  stamp(c: Chunk): ChunkStamp {
    const k = chunkKey(c.cx, c.cy, c.z);
    let s = this.stamps.get(k);
    if (!s) this.stamps.set(k, (s = { touched: this.game.clock.seconds, rot: 0 }));
    return s;
  }

  /** Bring one chunk up to date. */
  actualize(c: Chunk): void {
    const wasClean = this.tracking && c.items.size > 0 ? !this.tracking.isDirty(c) : false;
    this.actualizeInner(c);
    if (wasClean) this.tracking!.rebaseline(c);
  }

  private actualizeInner(c: Chunk): void {
    const game = this.game;
    const map = game.map;
    const now = game.clock.seconds;
    const st = this.stamp(c);
    const x0 = c.cx * CHUNK, y0 = c.cy * CHUNK;
    for (let i = 0; i < CHUNK * CHUNK; i++) {
      const x = x0 + (i % CHUNK), y = y0 + Math.floor(i / CHUNK);
      if (this.isHarvested(c.ter[i])) restockFruits(game, x, y, c.z, st.touched);
      if (c.furn[i] && hasFlag(map.furniture.defs[c.furn[i]], 'PLANT')) growPlant(game, x, y, c.z);
    }
    if (now - st.rot >= 60) {
      this.rotChunk(c, st.rot, now);
      st.rot = now;
    }
    st.touched = now;
  }

  /** Apply rot to every item lying in the chunk for game time [from, to). */
  rotChunk(c: Chunk, from: number, to: number): void {
    if (!c.items.size || to <= from) return;
    const map = this.game.map;
    // hour steps, coarser for very long absences so a year away stays cheap
    const step = Math.max(3600, (to - from) / 1000);
    const steps: [number, number][] = [];
    for (let t = from; t < to; t += step) steps.push([Math.min(step, to - t), this.hourTemp(t + Math.min(step, to - t) / 2)]);
    const x0 = c.cx * CHUNK, y0 = c.cy * CHUNK;
    for (const [li, list] of c.items) {
      const x = x0 + (li % CHUNK), y = y0 + Math.floor(li / CHUNK);
      const f = map.furniture.defs[c.furn[li]];
      // a planted seed doesn't rot (CDDA resets its age when planted and keeps it hidden)
      if (hasFlag(f, 'PLANT')) continue;
      const underground = c.z < 0;
      const indoors = !underground && !isOutside(map, x, y, c.z);
      const items = list as Item[];
      const affected = items.filter((it) => typeof it.processRot === 'function' && (it.goesBad() || it.hasContents()));
      if (!affected.length) continue;
      for (const [dt, T] of steps) {
        const temp = underground ? DEFAULT_WEATHER_GEN.base_temperature : indoors ? T + 3 : T;
        for (const it of affected) it.processRot(dt, temp);
      }
      // item::has_rotten_away: long-rotten food is gone (unless the furniture keeps rotten things)
      if (!hasFlag(f, 'DONT_REMOVE_ROTTEN'))
        destroyWhere(L.ground(map, x, y, c.z), (it) => affected.includes(it) && it.goesBad() && it.relativeRot() > 2);
    }
  }

  /** Actualize every loaded chunk within `radius` of the player (all z-levels in reach). */
  sweep(): number {
    const game = this.game;
    const p = game.player;
    const pcx = Math.floor(p.x / CHUNK), pcy = Math.floor(p.y / CHUNK);
    let n = 0;
    for (let z = p.z - 1; z <= p.z + 1; z++)
      for (let cy = pcy - this.radius; cy <= pcy + this.radius; cy++)
        for (let cx = pcx - this.radius; cx <= pcx + this.radius; cx++) {
          if (!game.map.hasChunk(cx, cy, z)) continue;
          this.actualize(game.map.chunk(cx, cy, z)!);
          n++;
        }
    return n;
  }

  update(gameDt: number): void {
    this.acc += gameDt;
    if (this.acc < this.interval) return;
    this.acc = 0;
    this.sweep();
  }

  /** Sweep on the next update (clock jumps, loads). */
  soon(): void {
    this.acc = Infinity;
  }

  /**
   * `keep`: which chunks' stamps to save. Chunks that aren't saved regenerate in their day-0
   * state on load, so their stamp must go too, or the regenerated food would skip the rot it
   * had already been given.
   */
  toJSON(keep: (key: string) => boolean = () => true): Record<string, [number, number]> {
    const o: Record<string, [number, number]> = {};
    for (const [k, s] of this.stamps) if (keep(k)) o[k] = [s.touched, s.rot];
    return o;
  }
  load(j: Record<string, [number, number]>): void {
    this.stamps.clear();
    for (const [k, [touched, rot]] of Object.entries(j)) this.stamps.set(k, { touched, rot });
    this.soon();
  }
}
