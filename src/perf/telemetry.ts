import { CHUNK, MAX_Z } from '../world/coords';
import type { ChunkEntryView, ChunkProbe } from '../render/chunkManager';

// Live performance telemetry: a rolling per-frame recording (last ~60 s) plus a log of
// streaming events (chunk wanted / generated / built / dropped), so "it struggles to load
// things when I drive through town" can be diagnosed from what actually happened on the
// player's machine instead of a guess. The overlay (overlay.ts) draws from it, Shift+F3 and
// `tools/live.ts perf` dump it, `tools/perf-report.ts` explains a dump.
//
// Cost model: sample() runs once per frame and writes ~50 floats into preallocated columns
// (a few microseconds); the streaming-health scan (holes in view, runway) iterates the chunk
// entries and runs at ~10 Hz. Per-kind mesher timing (`detail`) patches a few prototypes and
// costs real time (two performance.now() per call), so it is only on while the overlay shows.

/** Everything the telemetry reads from the running game; install.ts wires it. */
export interface TelemetrySource {
  player(): { x: number; y: number; z: number };
  /** camera forward on the ground plane (tile space x, y) and horizontal field of view (rad) */
  view(): { fx: number; fy: number; hfov: number };
  chunks: {
    radius: number;
    levelsBelow: number;
    levelsAbove: number;
    visibleDist: number;
    budgetMs: number;
    effBudgetMs: number;
    readonly stats: { entries: number; pending: number; builtThisFrame: number; meshMs: number; treeMs: number; frameCreateMs: number; frameMs: number; builds: number };
    forEachEntry(fn: (e: ChunkEntryView) => void): void;
  };
  /** fog fully opaque at this distance (tiles) */
  fogFar(): number;
  prefetch?: { stats: { queue: number }; inPrefetch: boolean };
  gl?: { calls: number; triangles: number; geometries: number; textures: number };
}

export type EventKind = 'want' | 'gen' | 'built' | 'rebuild' | 'trees' | 'empty' | 'drop' | 'evict';

export interface PerfEvent {
  t: number;
  k: EventKind;
  cx: number;
  cy: number;
  z: number;
  /** work ms (gen: exclusive mapgen time; built: summed step time) */
  ms?: number;
  /** built: ms from wanted to shown; rebuild: ms from start to finish */
  wait?: number;
  /** gen: generated by the prefetcher (idle time) instead of synchronously in a frame */
  pre?: boolean;
  omt?: string;
  /** drop: the entry had been shown */
  shown?: boolean;
}

/**
 * Frame columns, in dump order. Section names are frameStats laps (main.ts, renderer.ts,
 * chunkManager.ts); unknown laps land in `other`.
 */
export const CHANNELS = [
  // frame timing (ms)
  'interval', 'work', 'loop', 'wait',
  // main-loop sections (ms)
  'sim', 'chunkCreate', 'chunkSig', 'chunkBuild', 'grass', 'skyline', 'decor', 'sprites', 'beforeRender', 'lightmap', 'scene', 'draw', 'other',
  // GPU time of the frame's draw (ms, EXT_disjoint_timer_query; NaN where unsupported), lags 1-3 frames
  'gpu',
  // chunk meshing split (ms this frame): mesh data, 3D trees
  'mesh', 'trees',
  // mapgen (ms / count this frame): synchronous (inside a frame), prefetched (idle time), onChunkGenerated hooks
  'genSync', 'genPre', 'genHooks', 'genSyncN', 'genPreN',
  // mesher split by kind (ms this frame; `detail` only, else NaN)
  'kModels', 'kSurfaces', 'kDressing', 'kRooms',
  // player
  'px', 'py', 'pz', 'speed',
  // streaming health (scan at ~10 Hz, held between scans)
  'runwayM', 'runwayS', 'holesVis', 'holesFog', 'holesAll', 'wanted', 'built', 'building', 'oldestMs', 'pending',
  'entries', 'builds', 'prefetchQ', 'budget',
  // renderer / memory
  'calls', 'triangles', 'geometries', 'textures', 'heapMB',
] as const;
export type Channel = (typeof CHANNELS)[number];

const SECTION_CHANNEL: Record<string, Channel> = {
  game: 'sim', 'chunks.create': 'chunkCreate', 'chunks.sig': 'chunkSig', chunks: 'chunkBuild', grass: 'grass', skyline: 'skyline',
  decor: 'decor', sprites: 'sprites', beforeRender: 'beforeRender', lightmap: 'lightmap', scene: 'scene', draw: 'draw', wait: 'wait',
};

/** Rolling columnar frame store: capacity frames, newest overwrites oldest. */
export class FrameRing {
  readonly t: Float64Array;
  readonly cols: Record<Channel, Float32Array>;
  /** frames written in total (index of the next write = n % cap) */
  n = 0;
  constructor(readonly cap: number) {
    this.t = new Float64Array(cap);
    this.cols = Object.fromEntries(CHANNELS.map((c) => [c, new Float32Array(cap).fill(NaN)])) as Record<Channel, Float32Array>;
  }
  get size(): number {
    return Math.min(this.n, this.cap);
  }
  /** Physical index of the i-th frame back from the newest (0 = newest). */
  back(i: number): number {
    return (((this.n - 1 - i) % this.cap) + this.cap) % this.cap;
  }
  clear(): void {
    this.n = 0;
  }
}

/** Mesher sub-systems timed in detail mode (per-kind accumulators, exclusive time). */
export type MeshKind = 'kModels' | 'kSurfaces' | 'kDressing' | 'kRooms';

export class Telemetry implements ChunkProbe {
  readonly ring: FrameRing;
  readonly events: PerfEvent[] = [];
  private evHead = 0;
  /** events recorded in total */
  evN = 0;
  /** record frames and events (the rolling buffer); off = sample() is a no-op */
  recording = true;
  /** per-kind mesher timing (patches prototypes; install.ts toggles it with the overlay) */
  detail = false;
  readonly t0 = performance.now();
  // per-frame accumulators, reset in sample()
  private acc = { genSync: 0, genPre: 0, genHooks: 0, genSyncN: 0, genPreN: 0, kModels: 0, kSurfaces: 0, kDressing: 0, kRooms: 0 };
  private lastMesh = 0;
  private lastTree = 0;
  private lastBuilds = 0;
  private lastT = 0;
  private lastPos: { x: number; y: number; t: number } | null = null;
  private vel = { x: 0, y: 0 };
  private health = { runwayM: NaN, runwayS: NaN, holesVis: 0, holesFog: 0, holesAll: 0, wanted: 0, built: 0, building: 0, oldestMs: 0 };
  private scanT = 0;
  /** GPU ms results arrive late; the latest one is written into the next sample */
  gpuMs = NaN;
  heapMB: () => number = () => NaN;

  constructor(readonly src: TelemetrySource, opts: { frames?: number; events?: number } = {}) {
    this.ring = new FrameRing(opts.frames ?? 12000);
    this.evCap = opts.events ?? 30000;
  }
  private evCap: number;

  // ---- events --------------------------------------------------------------------------

  event(e: PerfEvent): void {
    if (!this.recording) return;
    if (this.events.length < this.evCap) this.events.push(e);
    else this.events[this.evHead] = e;
    this.evHead = (this.evHead + 1) % this.evCap;
    this.evN++;
  }

  /** Events oldest first. */
  eventList(): PerfEvent[] {
    if (this.events.length < this.evCap) return this.events.slice();
    return [...this.events.slice(this.evHead), ...this.events.slice(0, this.evHead)];
  }

  private now(): number {
    return performance.now() - this.t0;
  }

  // ChunkProbe
  want(cx: number, cy: number, z: number): void {
    this.event({ t: this.now(), k: 'want', cx, cy, z });
  }
  built(cx: number, cy: number, z: number, first: boolean, ms: number, wall: number, kind: 'full' | 'trees' | 'empty', waitMs: number): void {
    const k: EventKind = kind === 'empty' ? 'empty' : kind === 'trees' ? 'trees' : first ? 'built' : 'rebuild';
    this.event({ t: this.now(), k, cx, cy, z, ms: +ms.toFixed(2), wait: +(first ? waitMs : wall).toFixed(1) });
  }
  drop(cx: number, cy: number, z: number, shown: boolean): void {
    this.event({ t: this.now(), k: 'drop', cx, cy, z, shown });
  }

  /** A map chunk was generated: `ms` exclusive mapgen time. */
  generated(cx: number, cy: number, z: number, ms: number, pre: boolean, omt: string | undefined): void {
    if (pre) {
      this.acc.genPre += ms;
      this.acc.genPreN++;
    } else {
      this.acc.genSync += ms;
      this.acc.genSyncN++;
    }
    this.event({ t: this.now(), k: 'gen', cx, cy, z, ms: +ms.toFixed(2), pre, omt });
  }
  hooks(ms: number): void {
    this.acc.genHooks += ms;
  }
  kind(k: MeshKind, ms: number): void {
    this.acc[k] += ms;
  }

  // ---- per frame -----------------------------------------------------------------------

  /** Called by frameStats.sink once per frame, after render. */
  sample(workMs: number, rafNow: number, loopMs: number, sec: Readonly<Record<string, number>>): void {
    if (!this.recording) return;
    const r = this.ring;
    const i = r.n % r.cap;
    const C = r.cols;
    const t = rafNow - this.t0;
    r.t[i] = t;
    C.interval[i] = this.lastT ? t - this.lastT : NaN;
    this.lastT = t;
    C.work[i] = workMs;
    C.loop[i] = loopMs;
    // sections: known laps to their channels, the rest summed into `other`
    for (const c of ['sim', 'chunkCreate', 'chunkSig', 'chunkBuild', 'grass', 'skyline', 'decor', 'sprites', 'beforeRender', 'lightmap', 'scene', 'draw', 'wait', 'other'] as const) C[c][i] = 0;
    for (const k in sec) {
      const ch = SECTION_CHANNEL[k];
      if (ch) C[ch][i] += sec[k];
      else if (k !== 'prefetch') C.other[i] += sec[k];
    }
    C.gpu[i] = this.gpuMs;
    this.gpuMs = NaN;
    const cs = this.src.chunks.stats;
    C.mesh[i] = cs.meshMs - this.lastMesh;
    C.trees[i] = cs.treeMs - this.lastTree;
    this.lastMesh = cs.meshMs;
    this.lastTree = cs.treeMs;
    C.builds[i] = cs.builds - this.lastBuilds;
    this.lastBuilds = cs.builds;
    const a = this.acc;
    C.genSync[i] = a.genSync;
    C.genPre[i] = a.genPre;
    C.genHooks[i] = a.genHooks;
    C.genSyncN[i] = a.genSyncN;
    C.genPreN[i] = a.genPreN;
    for (const k of ['kModels', 'kSurfaces', 'kDressing', 'kRooms'] as const) C[k][i] = this.detail ? a[k] : NaN;
    a.genSync = a.genPre = a.genHooks = a.genSyncN = a.genPreN = a.kModels = a.kSurfaces = a.kDressing = a.kRooms = 0;

    const p = this.src.player();
    C.px[i] = p.x;
    C.py[i] = p.y;
    C.pz[i] = p.z;
    // speed from position deltas: covers walking, driving and scripted runs alike
    const l = this.lastPos;
    if (l && t > l.t) {
      const dt = (t - l.t) / 1000;
      const vx = (p.x - l.x) / dt, vy = (p.y - l.y) / dt;
      if (Math.hypot(vx, vy) < 80) {
        const k = Math.min(1, dt * 6);
        this.vel.x += (vx - this.vel.x) * k;
        this.vel.y += (vy - this.vel.y) * k;
      } else this.vel.x = this.vel.y = 0; // a teleport isn't movement
    }
    this.lastPos = { x: p.x, y: p.y, t };
    const speed = Math.hypot(this.vel.x, this.vel.y);
    C.speed[i] = speed;

    if (t - this.scanT >= 100 || r.n === 0) {
      this.scanT = t;
      this.scan(p, speed, rafNow);
    }
    const h = this.health;
    C.runwayM[i] = h.runwayM;
    C.runwayS[i] = h.runwayS;
    C.holesVis[i] = h.holesVis;
    C.holesFog[i] = h.holesFog;
    C.holesAll[i] = h.holesAll;
    C.wanted[i] = h.wanted;
    C.built[i] = h.built;
    C.building[i] = h.building;
    C.oldestMs[i] = h.oldestMs;
    C.pending[i] = cs.pending;
    C.entries[i] = cs.entries;
    C.prefetchQ[i] = this.src.prefetch?.stats.queue ?? NaN;
    C.budget[i] = this.src.chunks.effBudgetMs;
    const g = this.src.gl;
    C.calls[i] = g ? g.calls : NaN;
    C.triangles[i] = g ? g.triangles : NaN;
    C.geometries[i] = g ? g.geometries : NaN;
    C.textures[i] = g ? g.textures : NaN;
    C.heapMB[i] = (r.n & 31) === 0 ? this.heapMB() : C.heapMB[r.back(0)];
    r.n++;
  }

  // ---- streaming health ------------------------------------------------------------------

  private byKey = new Map<number, ChunkEntryView>();
  private offs: [number, number][] = [];
  private offsR = -1;

  /**
   * Holes = wanted chunks (player's level and the one above: roofs, upper floors) that are not
   * built yet, split by whether they are in the camera's horizontal field of view and inside the
   * clearly visible range (`visibleDist`) or the fog (`fogFar`). Runway = how far along the
   * direction of travel the world is built, in metres and in seconds at the current speed.
   */
  private scan(p: { x: number; y: number; z: number }, speed: number, rafNow: number): void {
    const ch = this.src.chunks;
    const R = ch.radius;
    const map = this.byKey;
    map.clear();
    const h = this.health;
    let wanted = 0, built = 0, building = 0, oldest = 0;
    const now = performance.now();
    const pz = p.z;
    ch.forEachEntry((e) => {
      map.set(ekey(e.cx, e.cy, e.z), e);
      if (e.z < pz - ch.levelsBelow || e.z > pz + ch.levelsAbove) return;
      wanted++;
      if (e.shown) built++;
      else oldest = Math.max(oldest, now - e.wantT);
      if (e.job) building++;
    });
    if (this.offsR !== R) {
      this.offs = [];
      for (let dy = -R; dy <= R; dy++) for (let dx = -R; dx <= R; dx++) if (dx * dx + dy * dy <= (R + 0.5) * (R + 0.5)) this.offs.push([dx, dy]);
      this.offsR = R;
    }
    const pcx = Math.floor(p.x / CHUNK), pcy = Math.floor(p.y / CHUNK);
    const v = this.src.view();
    const half = v.hfov / 2;
    const vis = ch.visibleDist, fog = this.src.fogFar();
    let hv = 0, hf = 0, ha = 0;
    const unbuilt = (cx: number, cy: number) => {
      for (let z = pz; z <= Math.min(MAX_Z, pz + 1); z++) {
        const e = map.get(ekey(cx, cy, z));
        if (!e || !e.shown) return true;
      }
      return false;
    };
    for (const [dx, dy] of this.offs) {
      const cx = pcx + dx, cy = pcy + dy;
      if (!unbuilt(cx, cy)) continue;
      ha++;
      // nearest point of the chunk to the player
      const nx = Math.max(cx * CHUNK, Math.min(p.x, cx * CHUNK + CHUNK)) - p.x;
      const ny = Math.max(cy * CHUNK, Math.min(p.y, cy * CHUNK + CHUNK)) - p.y;
      const d = Math.hypot(nx, ny);
      if (d > fog) continue;
      const ccx = cx * CHUNK + CHUNK / 2 - p.x, ccy = cy * CHUNK + CHUNK / 2 - p.y;
      const dc = Math.hypot(ccx, ccy);
      // in view: centre within the half-FOV plus the chunk's angular radius
      const inView = dc < CHUNK || Math.acos(Math.max(-1, Math.min(1, (ccx * v.fx + ccy * v.fy) / dc))) < half + Math.atan((CHUNK * 0.71) / dc);
      if (!inView) continue;
      hf++;
      if (d < vis) hv++;
    }
    h.holesVis = hv;
    h.holesFog = hf;
    h.holesAll = ha;
    h.wanted = wanted;
    h.built = built;
    h.building = building;
    h.oldestMs = oldest;
    // runway along the velocity (three rays, 0 and +-12 degrees): the first unbuilt chunk
    const maxM = (R + 0.5) * CHUNK;
    if (speed < 1.5) {
      h.runwayM = NaN;
      h.runwayS = NaN;
    } else {
      const ux = this.vel.x / speed, uy = this.vel.y / speed;
      let best = maxM;
      for (const a of [0, 0.21, -0.21]) {
        const c = Math.cos(a), s = Math.sin(a);
        const rx = ux * c - uy * s, ry = ux * s + uy * c;
        for (let dist = 0; dist < best; dist += 3) {
          const tx = p.x + rx * dist, ty = p.y + ry * dist;
          if (unbuilt(Math.floor(tx / CHUNK), Math.floor(ty / CHUNK))) {
            best = dist;
            break;
          }
        }
      }
      h.runwayM = best;
      h.runwayS = best / speed;
    }
    void rafNow;
  }

  /** Current smoothed velocity (tiles/s). */
  velocity(): { x: number; y: number } {
    return this.vel;
  }

  reset(): void {
    this.ring.clear();
    this.events.length = 0;
    this.evHead = 0;
    this.evN = 0;
  }
}

const ekey = (cx: number, cy: number, z: number) => ((z + 16) * 4096 + (cx + 2048)) * 4096 + (cy + 2048);
